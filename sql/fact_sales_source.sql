-- Requête SELECT extraite de P_Fait_Ventes.dtsx.
-- Documentation de la transformation existante ; aucun script de création des bases.

SELECT 
    -- 1. Keys
    D.REF_PRODUIT,
    C.CODE_CLIENT,
    (YEAR(C.DATE_COMMANDE) * 10000 + MONTH(C.DATE_COMMANDE) * 100 + DAY(C.DATE_COMMANDE)) AS DATE_KEY,

    -- 2. Infos Commande
    C.NUM_COMMANDE,
    C.VILLE_LIVRAISON,
    C.PAYS_LIVRAISON,

    -- 3. Data Cleaning (Imputation)
    ISNULL(C.PORT, Moyenne.GlobalAvgPort) AS PORT_CLEAN,

    -- 4. Mesures
    D.QUANTITE,
    P.PRIX_UNITAIRE,
    ISNULL(D.REMISE, 0) AS REMISE,

    -- 5. Calculs (KPIs)
    CAST((D.QUANTITE * P.PRIX_UNITAIRE) AS DECIMAL(12,2)) AS MONTANT_BRUT,
    CAST((D.QUANTITE * P.PRIX_UNITAIRE * (1 - ISNULL(D.REMISE, 0))) AS DECIMAL(12,2)) AS MONTANT_NET,
    
    -- Calcul Retard
    DATEDIFF(day, C.DATE_COMMANDE, C.DATE_LIVRAISON) AS RETARD_LIVRAISON

FROM COMPTOIR_DETAILS_COMMANDE D
INNER JOIN COMPTOIR_COMMANDES C ON D.NUM_COMMANDE = C.NUM_COMMANDE
INNER JOIN COMPTOIR_PRODUITS P ON D.REF_PRODUIT = P.REF_PRODUIT
CROSS JOIN (
    SELECT AVG(PORT) AS GlobalAvgPort FROM COMPTOIR_COMMANDES
) Moyenne

-- === CORRECTION (CLEANING) ===
WHERE C.CODE_CLIENT IS NOT NULL 
  AND D.REF_PRODUIT IS NOT NULL
  AND C.DATE_COMMANDE IS NOT NULL
